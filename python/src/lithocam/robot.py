@dataclass
class ReachFace:
    index: int
    rulings: int
    reachable: int
    best_rolls: List[Optional[float]] = field(default_factory=list)


@dataclass
class ReachReport:
    cell: str
    placement: List[float]
    faces: List[ReachFace]

    @property
    def fraction(self) -> float:
        tot = sum(f.rulings for f in self.faces)
        return sum(f.reachable for f in self.faces) / tot if tot else 0.0


def wire_reach(cell: Cell, ruled_report, placement: Sequence[float] = (0.6, 0.0, 0.0), units: float = 1e-3,
               bow_depth: float = 0.25, roll_deg: Sequence[float] = (-60, -40, -20, 0, 20, 40, 60),
               labels: Sequence[str] = ("wire",)) -> ReachReport:
    """Reachability of every ruling on faces with the given labels.

    placement: translation of the part's model origin in the robot base frame (metres).
    units: model units to metres (1e-3 for mm).
    """
    off = np.asarray(placement, dtype=np.float64)
    wr = ruled_report.rules.wire_diameter / 2 * units
    faces = []
    seed = None
    for f in ruled_report.faces:
        if f.label not in labels or not f.rulings:
            continue
        rf = ReachFace(f.index, len(f.rulings), 0)
        for r in f.rulings:
            p0 = np.asarray(r.p0) * units + off
            p1 = np.asarray(r.p1) * units + off
            best = None
            for a in roll_deg:
                sols = cell.ik(wire_target(p0, p1, r.normal, wr, math.radians(a), bow_depth), seed)
                if sols:
                    best = a
                    seed = sols[0]
                    break
            rf.best_rolls.append(best)
            rf.reachable += best is not None
        faces.append(rf)
    return ReachReport(cell.name, list(off), faces)


@dataclass
class JointPath:
    joints: List[np.ndarray]          # one configuration per target, in target order
    targets: List[np.ndarray]         # the tool0 poses (4x4, base frame)
    rolls: List[float]                # chosen roll about the wire per target (degrees)
    max_step: float                   # largest joint change between consecutive targets (radians)
    missing: List[int]                # target indices with no solution (path is broken there)


def wire_face_path(cell: Cell, face, wire_radius: float, placement: Sequence[float], units: float = 1e-3,
                   bow_depth: float = 0.25, roll_deg: Sequence[float] = tuple(range(-60, 61, 10)),
                   seed: Optional[np.ndarray] = None, try_starts: int = 8) -> JointPath:
    """Without a seed, every (collision-free) IK branch of the first ruling is tried as the start and the path with
    the smallest largest joint step is kept; with a seed the path continues from it."""
    if seed is not None or try_starts <= 1:
        return _wire_face_path(cell, face, wire_radius, placement, units, bow_depth, roll_deg, seed)
    first = _wire_face_path(cell, face, wire_radius, placement, units, bow_depth, roll_deg, None)
    if not first.joints:
        return first
    T0 = first.targets[0]
    starts = cell.collision_free([w for s in cell.ik(T0) for w in cell.wrap_variants(s)])[:try_starts]
    best = first
    for q0 in starts:
        jp = _wire_face_path(cell, face, wire_radius, placement, units, bow_depth, roll_deg, q0)
        if len(jp.missing) <= len(best.missing) and jp.max_step < best.max_step:
            best = jp
    return best


def _wire_face_path(cell: Cell, face, wire_radius: float, placement: Sequence[float], units: float = 1e-3,
                    bow_depth: float = 0.25, roll_deg: Sequence[float] = tuple(range(-60, 61, 10)),
                    seed: Optional[np.ndarray] = None) -> JointPath:
    """Joint path for sweeping the wire across one face, ruling by ruling.

    Rulings are ordered along the sweep (by their midpoints' projection on the main sweep direction). For each
    ruling, rolls are tried nearest-first to the previous roll, and among the verified IK solutions the one
    closest to the previous configuration (max absolute joint change) is kept.
    """
    off = np.asarray(placement, dtype=np.float64)
    rs = list(face.rulings)
    mids = np.array([(np.asarray(r.p0) + np.asarray(r.p1)) / 2 for r in rs])
    if len(rs) > 1:
        c = mids - mids.mean(axis=0)
        sweep = np.linalg.svd(c, full_matrices=False)[2][0]
        order = np.argsort(c @ sweep)
        rs = [rs[i] for i in order]
    prev_q = seed if seed is not None else None
    prev_roll = 0.0
    joints, targets, rolls, missing = [], [], [], []
    for k, r in enumerate(rs):
        p0 = np.asarray(r.p0) * units + off
        p1 = np.asarray(r.p1) * units + off
        best = None
        for a in sorted(roll_deg, key=lambda v: abs(v - prev_roll)):
            T = wire_target(p0, p1, r.normal, wire_radius, math.radians(a), bow_depth)
            sols = cell.ik(T, prev_q)
            if not sols:
                continue
            sols = cell.collision_free([w for s in sols for w in cell.wrap_variants(s)])
            if not sols:
                continue
            q = sols[0] if prev_q is None else min(sols, key=lambda s: float(np.max(np.abs(s - prev_q))))
            step = 0.0 if prev_q is None else float(np.max(np.abs(q - prev_q)))
            if best is None or step < best[0] - 1e-9:
                best = (step, q, T, a)
            if step < math.radians(15):
                break
        if best is None:
            missing.append(k)
            continue
        _, q, T, a = best
        joints.append(q)
        targets.append(T)
        rolls.append(a)
        prev_q, prev_roll = q, a
    steps = [float(np.max(np.abs(joints[i] - joints[i - 1]))) for i in range(1, len(joints))]
    return JointPath(joints, targets, rolls, max(steps) if steps else 0.0, missing)


def axis_target(tip, axis, spindle: float, spin: float) -> np.ndarray:
    """tool0 pose for a spindle whose tool axis is tool z: the tip sits `spindle` metres along z from tool0, the
    tool axis (tip -> shank) points against tool z, and `spin` turns the pose about the axis (free for a rotating
    cutter: the 5-axis redundancy)."""
    tip, axis = np.asarray(tip, float), np.asarray(axis, float) / np.linalg.norm(axis)
    z = -axis
    a = np.array([1.0, 0, 0]) if abs(z[0]) < 0.9 else np.array([0, 1.0, 0])
    x = np.cross(a, z)
    x /= np.linalg.norm(x)
    y = np.cross(z, x)
    R = np.column_stack([x, y, z]) @ np.array([[math.cos(spin), -math.sin(spin), 0],
                                               [math.sin(spin), math.cos(spin), 0], [0, 0, 1]])
    T = np.eye(4)
    T[:3, :3] = R
    T[:3, 3] = tip - z * spindle
    return T


def axis_path(cell: Cell, tips, axes, spindle: float, placement: Sequence[float], units: float = 1e-3,
              spin_deg: Sequence[float] = tuple(range(-180, 180, 15)), seed: Optional[np.ndarray] = None) -> JointPath:
    """Joint path for 5-axis CL frames (tool tip + tool axis): spin tried nearest-first, verified IK, closest
    configuration (2 pi wrap variants included)."""
    off = np.asarray(placement, float)
    prev_q, prev_spin = seed, 0.0
    joints, targets, spins, missing = [], [], [], []
    for k, (p, a) in enumerate(zip(tips, axes)):
        best = None
        for s in sorted(spin_deg, key=lambda v: abs(((v - prev_spin) + 180) % 360 - 180)):
            T = axis_target(np.asarray(p) * units + off, a, spindle, math.radians(s))
            sols = cell.ik(T, prev_q)
            if not sols:
                continue
            sols = cell.collision_free([w for q in sols for w in cell.wrap_variants(q)])
            if not sols:
                continue
            q = sols[0] if prev_q is None else min(sols, key=lambda v: float(np.max(np.abs(v - prev_q))))
            step = 0.0 if prev_q is None else float(np.max(np.abs(q - prev_q)))
            if best is None or step < best[0] - 1e-9:
                best = (step, q, T, s)
            if step < math.radians(10):
                break
        if best is None:
            missing.append(k)
            continue
        _, q, T, s = best
        joints.append(q)
        targets.append(T)
        spins.append(s)
        prev_q, prev_spin = q, s
    steps = [float(np.max(np.abs(joints[i] - joints[i - 1]))) for i in range(1, len(joints))]
    return JointPath(joints, targets, spins, max(steps) if steps else 0.0, missing)


@dataclass
class Positioners:
    """External axes, sampled: a linear track under the robot along world x, and a turntable under the part.

    track:        robot base x positions (metres) the track may take
    table_deg:    turntable angles (degrees) the table may take
    table_center: world point on the turntable's vertical axis; the part's `placement` is given relative to it
    """
    track: Sequence[float] = (0.0,)
    table_deg: Sequence[float] = (0.0,)
    table_center: Sequence[float] = (0.0, 0.0, 0.0)


def _rz(deg: float) -> np.ndarray:
    a = math.radians(deg)
    c, s = math.cos(a), math.sin(a)
    T = np.eye(4)
    T[:2, :2] = [[c, -s], [s, c]]
    return T


@dataclass
class ExtReach:
    rulings: int
    reachable: int
    choices: List[Optional[tuple]]     # per ruling: (track x, table deg, roll deg) or None

    @property
    def fraction(self) -> float:
        return self.reachable / self.rulings if self.rulings else 0.0


def wire_reach_ext(cell: Cell, ruled_report, placement: Sequence[float], pos: Positioners, units: float = 1e-3,
                   bow_depth: float = 0.25, roll_deg: Sequence[float] = (-60, -30, 0, 30, 60),
                   labels: Sequence[str] = ("wire",)) -> ExtReach:
    """Like wire_reach, with a sampled track and turntable. Choices are tried nearest-first to the previous ones."""
    wr = ruled_report.rules.wire_diameter / 2 * units
    Tc = np.eye(4)
    Tc[:3, 3] = pos.table_center
    Tp = np.eye(4)
    Tp[:3, 3] = placement
    rulings, choices = 0, []
    prev = (pos.track[0], pos.table_deg[0], 0.0)
    seed = None
    for f in ruled_report.faces:
        if f.label not in labels or not f.rulings:
            continue
        for r in f.rulings:
            rulings += 1
            found = None
            for tdeg in sorted(pos.table_deg, key=lambda v: abs(v - prev[1])):
                W = Tc @ _rz(tdeg) @ Tp                     # part model frame -> world
                p0 = (W @ np.r_[np.asarray(r.p0) * units, 1.0])[:3]
                p1 = (W @ np.r_[np.asarray(r.p1) * units, 1.0])[:3]
                n = W[:3, :3] @ np.asarray(r.normal)
                for tx in sorted(pos.track, key=lambda v: abs(v - prev[0])):
                    shift = np.array([tx, 0.0, 0.0])
                    for a in sorted(roll_deg, key=lambda v: abs(v - prev[2])):
                        T = wire_target(p0 - shift, p1 - shift, n, wr, math.radians(a), bow_depth)
                        sols = cell.ik(T, seed)
                        if sols:
                            found = (tx, tdeg, a)
                            seed = sols[0]
                            break
                    if found:
                        break
                if found:
                    break
            choices.append(found)
            if found:
                prev = found
    return ExtReach(rulings, sum(c is not None for c in choices), choices)


def summary(rep: ReachReport) -> Dict[str, object]:
    return {"cell": rep.cell, "placement": rep.placement, "fraction": round(rep.fraction, 4),
            "faces": {f.index: "{}/{}".format(f.reachable, f.rulings) for f in rep.faces}}


def main(argv=None) -> int:
    import argparse  # noqa: PLC0415
    import json  # noqa: PLC0415

    ap = argparse.ArgumentParser(prog="python -m lithocam.robot", description="Wire-ruling reachability in a cell")
    ap.add_argument("ruled_json", help="output of python -m lithocam.ruled part.step --json faces.json")
    ap.add_argument("--cell", default="ur10e")
    ap.add_argument("--placement", default="0.6,0,0", help="part origin in the robot base frame, metres: x,y,z")
    ap.add_argument("--units", type=float, default=1e-3)
    ap.add_argument("--bow-depth", type=float, default=0.25)
    a = ap.parse_args(argv)
    rep = wire_reach(Cell(a.cell), load_ruled_json(a.ruled_json), [float(v) for v in a.placement.split(",")],
                     a.units, a.bow_depth)
    print(json.dumps(summary(rep)))
    return 0


