"""Robot cells in Tesseract: verified inverse kinematics and reachability of wire-saw rulings.

Cells live in the repository's `cells/` folder (URDF + SRDF + kinematics plugins, generated by
`cells/make_cells.py`): `ur10e` and `kr120` (KUKA KR120 R2500 PRO).

**IK is verified.** The analytic solvers (Tesseract's UR solver for the UR10e, OPW for the KR120) are used for
speed, but every solution is checked against forward kinematics and dropped if it misses the target. When no
analytic solution survives, the numerical KDL solver is run from several seeds. With the cell files as written,
the analytic solvers agree with KDL on most poses but not all (UR10e about 83 percent of solutions, KR120 about
54 percent), so this check is required, not optional.

**Wire reachability.** A wire bow holds the wire along the tool's x axis at `bow_depth` in front of the flange
(tool z). For each `wire` ruling from `lithocam.ruled`, the target puts the wire on the kerf-offset ruling line
(offset by the wire radius along the face normal), with the tool z axis against the face normal. The free
rotation about the wire is sampled (`roll_deg`); a ruling is reachable when some roll has an IK solution inside
the joint limits.

Not checked yet: collisions between the robot, the bow and the part; joint continuity along a sweep; external
axes (track, turntable). Those are the next steps.

Needs tesseract-robotics (`pip install tesseract-robotics`).
"""
from __future__ import annotations

import math
import os
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Sequence

import numpy as np

CELLS = Path(__file__).resolve().parents[3] / "cells"
os.environ.setdefault("TESSERACT_RESOURCE_PATH", str(CELLS.parent))

from tesseract_robotics.tesseract_common import FilesystemPath, GeneralResourceLocator, Isometry3d  # noqa: E402
from tesseract_robotics.tesseract_environment import Environment  # noqa: E402
from tesseract_robotics.tesseract_kinematics import KinGroupIKInput, KinGroupIKInputs  # noqa: E402

TIP, BASE = "tool0", "base_link"


def _iso(T: np.ndarray):
    iso = Isometry3d.Identity()
    iso.setMatrix(np.asarray(T, dtype=np.float64)) if hasattr(iso, "setMatrix") else None
    if not hasattr(iso, "setMatrix"):
        iso = Isometry3d(np.asarray(T, dtype=np.float64))
    return iso


class Cell:
    """One robot cell: forward kinematics and verified inverse kinematics of group `manipulator`."""

    def __init__(self, name: str, cells_dir: Optional[Path] = None):
        d = Path(cells_dir) if cells_dir else CELLS
        self.name = name
        self.env = Environment()
        if not self.env.init(FilesystemPath(str(d / (name + ".urdf"))), FilesystemPath(str(d / (name + ".srdf"))),
                             GeneralResourceLocator()):
            raise RuntimeError("cannot load cell {} from {}".format(name, d))
        self.kin = self.env.getKinematicGroup("manipulator")
        try:
            self.kdl = self.env.getKinematicGroup("manipulator", "KDLInvKinChainLMA")
        except Exception:  # noqa: BLE001
            self.kdl = None
        self.joint_names = list(self.kin.getJointNames())
        self.limits = np.asarray(self.kin.getLimits().joint_limits, dtype=np.float64)

    def fk(self, q: Sequence[float]) -> np.ndarray:
        return np.asarray(self.kin.calcFwdKin(np.asarray(q, dtype=np.float64))[TIP].matrix())

    def _raw_ik(self, group, T: np.ndarray, seed: np.ndarray) -> List[np.ndarray]:
        ik = KinGroupIKInput()
        ik.pose = _iso(T)
        ik.tip_link_name = TIP
        ik.working_frame = BASE
        iks = KinGroupIKInputs()
        iks.append(ik)
        try:
            sols = group.calcInvKin(iks, np.asarray(seed, dtype=np.float64))
        except Exception:  # noqa: BLE001  (KDL throws when it does not converge)
            return []
        return [np.asarray(sols[i], dtype=np.float64).flatten() for i in range(len(sols))]

    def within_limits(self, q: np.ndarray) -> bool:
        return bool(np.all(q >= self.limits[:, 0] - 1e-9) and np.all(q <= self.limits[:, 1] + 1e-9))

    def ik(self, T: np.ndarray, seed: Optional[np.ndarray] = None, tol: float = 1e-6, n_seeds: int = 6
           ) -> List[np.ndarray]:
        """Joint solutions inside the limits whose forward kinematics reach T (pose of tool0 in base_link)."""
        seed = np.zeros(len(self.joint_names)) if seed is None else np.asarray(seed, dtype=np.float64)

        def good(q):
            return self.within_limits(q) and np.linalg.norm(self.fk(q) - T) < tol

        sols = [q for q in self._raw_ik(self.kin, T, seed) if good(q)]
        if sols or self.kdl is None:
            return sols
        rng = np.random.default_rng(0)
        seeds = [seed] + [self.limits[:, 0] + rng.random(len(seed)) * (self.limits[:, 1] - self.limits[:, 0])
                          for _ in range(n_seeds - 1)]
        for s in seeds:
            sols = [q for q in self._raw_ik(self.kdl, T, s) if good(q)]
            if sols:
                return sols
        return []


# ---------------------------------------------------------------- wire-saw targets

def rot_x(a: float) -> np.ndarray:
    c, s = math.cos(a), math.sin(a)
    return np.array([[1, 0, 0], [0, c, -s], [0, s, c]], dtype=np.float64)


def wire_target(p0, p1, normal, wire_radius: float, roll: float, bow_depth: float) -> np.ndarray:
    """tool0 pose (4x4) that puts the wire (tool x axis, at bow_depth along tool z) on the kerf-offset ruling.

    Units are metres. The tool z axis points against the face normal (the bow reaches over the cut), turned by
    `roll` about the wire.
    """
    p0, p1, n = (np.asarray(v, dtype=np.float64) for v in (p0, p1, normal))
    x = p1 - p0
    x /= np.linalg.norm(x)
    z = -(n - np.dot(n, x) * x)
    z /= np.linalg.norm(z)
    y = np.cross(z, x)
    R = np.column_stack([x, y, z]) @ rot_x(roll)
    mid = 0.5 * (p0 + p1) + n * wire_radius
    T = np.eye(4)
    T[:3, :3] = R
    T[:3, 3] = mid - R[:, 2] * bow_depth          # tool0 sits bow_depth behind the wire along tool z
    return T


@dataclass
class ReachFace:
    index: int
    rulings: int
    reachable: int
    best_rolls: List[Optional[float]] = field(default_factory=list)


@dataclass
class ReachReport:
    cell: str
    placement: List[float]
    faces: List[ReachFace]

    @property
    def fraction(self) -> float:
        tot = sum(f.rulings for f in self.faces)
        return sum(f.reachable for f in self.faces) / tot if tot else 0.0


def wire_reach(cell: Cell, ruled_report, placement: Sequence[float] = (0.6, 0.0, 0.0), units: float = 1e-3,
               bow_depth: float = 0.25, roll_deg: Sequence[float] = (-60, -40, -20, 0, 20, 40, 60),
               labels: Sequence[str] = ("wire",)) -> ReachReport:
    """Reachability of every ruling on faces with the given labels.

    placement: translation of the part's model origin in the robot base frame (metres).
    units: model units to metres (1e-3 for mm).
    """
    off = np.asarray(placement, dtype=np.float64)
    wr = ruled_report.rules.wire_diameter / 2 * units
    faces = []
    seed = None
    for f in ruled_report.faces:
        if f.label not in labels or not f.rulings:
            continue
        rf = ReachFace(f.index, len(f.rulings), 0)
        for r in f.rulings:
            p0 = np.asarray(r.p0) * units + off
            p1 = np.asarray(r.p1) * units + off
            best = None
            for a in roll_deg:
                sols = cell.ik(wire_target(p0, p1, r.normal, wr, math.radians(a), bow_depth), seed)
                if sols:
                    best = a
                    seed = sols[0]
                    break
            rf.best_rolls.append(best)
            rf.reachable += best is not None
        faces.append(rf)
    return ReachReport(cell.name, list(off), faces)


def summary(rep: ReachReport) -> Dict[str, object]:
    return {"cell": rep.cell, "placement": rep.placement, "fraction": round(rep.fraction, 4),
            "faces": {f.index: "{}/{}".format(f.reachable, f.rulings) for f in rep.faces}}


def load_ruled_json(path: str):
    """Read `python -m lithocam.ruled ... --json` output into objects with the attributes wire_reach uses.

    This keeps the OCP environment (ruled) and the Tesseract environment (robot) separate.
    """
    import json  # noqa: PLC0415
    from types import SimpleNamespace as NS  # noqa: PLC0415

    d = json.loads(Path(path).read_text(encoding="utf-8"))
    faces = [NS(index=f["index"], label=f["label"], rulings=[NS(**r) for r in f["rulings"]]) for f in d["faces"]]
    return NS(faces=faces, rules=NS(**d["rules"]), scale=d["scale"])


def main(argv=None) -> int:
    import argparse  # noqa: PLC0415
    import json  # noqa: PLC0415

    ap = argparse.ArgumentParser(prog="python -m lithocam.robot", description="Wire-ruling reachability in a cell")
    ap.add_argument("ruled_json", help="output of python -m lithocam.ruled part.step --json faces.json")
    ap.add_argument("--cell", default="ur10e")
    ap.add_argument("--placement", default="0.6,0,0", help="part origin in the robot base frame, metres: x,y,z")
    ap.add_argument("--units", type=float, default=1e-3)
    ap.add_argument("--bow-depth", type=float, default=0.25)
    a = ap.parse_args(argv)
    rep = wire_reach(Cell(a.cell), load_ruled_json(a.ruled_json), [float(v) for v in a.placement.split(",")],
                     a.units, a.bow_depth)
    print(json.dumps(summary(rep)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
